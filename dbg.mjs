import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: '/usr/local/bin/google-chrome', args: ['--use-angle=swiftshader','--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
p.on('console', m => { if (!m.text().includes('WebSocket')) console.log(m.type(), m.text().slice(0,300)); });
p.on('pageerror', e => console.log('pageerror', e.message));
p.on('requestfailed', r => console.log('failed', r.url(), r.failure()?.errorText));
p.on('request', r => { if (r.url().includes('data/')||r.url().includes('tiles/')) console.log('req', r.url()); }); p.on('response', r => { if (r.status() >= 400) console.log('status', r.status(), r.url()); });
await p.goto('http://127.0.0.1:4317/', { waitUntil: 'networkidle' });
await p.waitForTimeout(5000);
const reqs=[]; console.log(await p.evaluate(() => document.querySelectorAll('canvas').length + ' canvases; panel text: ' + document.querySelector('aside')?.innerText.slice(0,200)));
await b.close();
